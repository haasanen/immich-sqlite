// Phase 2: generate fresh-install SQLite DDL from immich's sql-tools schema.
// schemaFromCode() is the single source of truth (the decorators), so this
// replaces hand-porting the 102 PG migrations. Emits only what SQLite can
// represent; every skip is recorded in the report. Vector columns (synchronize:
// false) get their own vec0 shadow tables, emitted separately.
import { schemaFromCode } from '@immich/sql-tools';

// Generated columns populated by AFTER INSERT triggers (SQLite cannot assign
// NEW in BEFORE triggers): insert-time NOT NULL would reject the row before
// the backfill trigger runs. Nullable in SQLite; the trigger guarantees the
// value on every insert.
const RELAX_NOTNULL = new Set(['asset_face.ownerId', 'asset_face.assetVisibility', 'plugin_method.uiHints']);
import 'src/schema/index.js';
// Side-effect imports: these table modules are only referenced via `import
// type` elsewhere, so TS erases them and their decorators never register.
// The probes/audit comparing src/schema/index.ts DB keys against generated
// tables catches any future drift.
import 'src/schema/tables/asset-av.table.js';
import 'src/schema/tables/workflow-log.table.js';
import { writeFileSync } from 'node:fs';

const schema = schemaFromCode();
const report: Record<string, any> = {
  skippedColumns: [],
  skippedTriggers: [],
  skippedIndexes: [],
  translatedTriggers: [],
  untranslatedTriggers: [],
  booleanChecks: 0,
};

const q = (s: string) => `"${s}"`;

const mapType = (c: any): string => {
  if (c.isArray) return 'text'; // PG array -> JSON text
  if (c.type === 'enum') {
    const anyc = c as unknown as { enum?: unknown; values?: unknown };
    const raw = anyc.enum ?? anyc.values;
    const vals = Array.isArray(raw)
      ? raw
      : raw && typeof raw === 'object'
        ? Object.values(raw as Record<string, unknown>)
        : [];
    return vals.length > 0 && vals.every((v) => Number.isFinite(v as number)) ? 'integer' : 'text';
  }
  switch (c.type) {
    case 'uuid':
      return 'text';
    case 'character varying':
    case 'character':
    case 'text':
    case 'citext':
      return 'text';
    case 'timestamp with time zone':
    case 'timestamp':
    case 'date':
      return 'text';
    case 'boolean':
      return 'integer';
    case 'integer':
    case 'smallint':
    case 'bigint':
      return 'integer';
    case 'real':
    case 'double precision':
    case 'numeric':
      return 'real';
    case 'bytea':
      return 'blob';
    case 'jsonb':
    case 'json':
      return 'text';
    case 'polygon':
      return 'text';
    case 'vector':
      // stored as pgvector-style text ("[0.1,0.2]"); scalar distance fns
      // implement the operators. sqlite-vec vec0 is the scale-up path.
      return 'text';
    default:
      return 'text';
  }
};

const mapDefault = (d: any, sqlType: string): string | null => {
  if (d === undefined || d === null) return null;
  const s = String(d).trim();
  if (s === 'now()' || s === 'clock_timestamp()') return `(now_iso())`;
  if (s === 'immich_uuid_v7()' || s === 'uuidv7()') return '(uuidv7())'; // registered scalar function
  if (s === 'false') return '0';
  if (s === 'true') return '1';
  if (s === "'{}'") return "'[]'"; // empty PG array -> empty JSON
  if (sqlType === 'integer' && /^\d+$/.test(s)) return s;
  if (/^-?\d+(\.\d+)?$/.test(s)) return s;
  if (/^'.*'$/.test(s)) return s; // string literal
  return null;
};

const fixCheck = (expr: string): string =>
  expr
    .replace(/("[^"]+")\s*<=\s*CURRENT_DATE/g, 'date($1) <= CURRENT_DATE')
    .replace(/("[^"]+")\s*>=\s*CURRENT_DATE/g, 'date($1) >= CURRENT_DATE')
    .replace(/=\s*true\b/g, '= 1')
    .replace(/=\s*false\b/g, '= 0')
    .replace(/!=\s*true\b/g, '!= 1')
    .replace(/!=\s*false\b/g, '!= 0');

const actions = new Set(['NO ACTION', 'RESTRICT', 'SET NULL', 'SET DEFAULT', 'CASCADE']);
const mapAction = (a?: string): string | undefined => {
  if (!a) return undefined;
  if (a.toUpperCase() === 'NO ACTION' || a.toUpperCase() === 'RESTRICT') return 'NO ACTION';
  return actions.has(a.toUpperCase()) ? a.toUpperCase() : 'NO ACTION';
};

const lines: string[] = [];
lines.push('-- Generated by server/probes/gen-sqlite-schema.ts from immich sql-tools schema.');
lines.push('-- Fresh-install SQLite schema only. Do not edit by hand; regenerate.');
lines.push('PRAGMA foreign_keys = ON;');
lines.push('');

for (const t of schema.tables.sort((a, b) => a.name.localeCompare(b.name))) {
  const cols: string[] = [];
  const pkCols = t.constraints.find((c) => c.type === 'primary-key')?.columnNames ?? [];
  for (const c of t.columns) {
    if (c.synchronize === false && c.type !== 'vector') {
      report.skippedColumns.push(`${t.name}.${c.name} (${c.type})`);
      continue;
    }
    const st = mapType(c);
    let d = `${q(c.name)} ${st}`;
    if (pkCols.length === 1 && pkCols[0] === c.name) d += ' primary key';
    else if (!c.nullable && !pkCols.includes(c.name) && !RELAX_NOTNULL.has(`${t.name}.${c.name}`)) d += ' not null';

    const def = mapDefault((c as any).default, st);
    if (def) d += ` default ${def}`;
    const isUq = t.constraints.some(
      (c2) => c2.type === 'unique' && c2.columnNames.length === 1 && c2.columnNames[0] === c.name,
    );
    if (isUq && !c.primary) d += ' unique';
    cols.push('  ' + d);
  }

  for (const con of t.constraints) {
    if (con.type === 'primary-key') {
      if (pkCols.length > 1) cols.push(`  primary key (${pkCols.map(q).join(', ')})`);
    } else if (con.type === 'foreign-key') {
      const od = mapAction((con as any).onDelete);
      const ou = mapAction((con as any).onUpdate);
      let d = `  constraint ${q(con.name)} foreign key (${con.columnNames.map(q).join(', ')}) references ${q(con.referenceTableName!)} (${con.referenceColumnNames!.map(q).join(', ')})`;
      if (od && od !== 'NO ACTION') d += ` on delete ${od}`;
      if (ou && ou !== 'NO ACTION') d += ` on update ${ou}`;
      cols.push(d);
    } else if (con.type === 'unique') {
      cols.push(`  constraint ${q(con.name)} unique (${con.columnNames.map(q).join(', ')})`);
    } else if (con.type === 'check') {
      report.booleanChecks++;
      cols.push(`  constraint ${q(con.name)} check (${fixCheck(con.expression!)})`);
    }
  }

  lines.push(`create table ${q(t.name)} (`);
  lines.push(cols.join(',\n'));
  lines.push(');');
  lines.push('');

  for (const idx of t.indexes) {
    if (idx.synchronize === false) {
      report.skippedIndexes.push(`${t.name}.${idx.name}`);
      continue;
    }
    if (!idx.columnNames || idx.columnNames.length === 0) {
      report.skippedIndexes.push(`${t.name}.${idx.name} (expression index)`);
      continue;
    }
    const uniq = idx.unique ? 'unique ' : '';
    const pred = ((idx as any).predicate ?? (idx as any).where) as string | undefined;
    const where = pred ? ` where ${fixCheck(pred)}` : '';
    lines.push(
      `create ${uniq}index ${q(idx.name)} on ${q(t.name)} (${(idx.columnNames ?? []).map(q).join(', ')})${where};`,
    );
  }

  for (const tr of t.triggers) {
    report.skippedTriggers.push(`${t.name}.${tr.name}`);
  }
  if (t.indexes.length) lines.push('');
}

// ---- trigger translation -------------------------------------------------
const fnBodies = new Map(schema.functions.map((f) => [f.name, f.expression ?? '']));
const pkColsOf = (tableName: string): string[] =>
  schema.tables.find((x) => x.name === tableName)?.constraints.find((c) => c.type === 'primary-key')?.columnNames ?? [];

const prefixRefs = (exprs: string, ref: 'old' | 'new'): string =>
  exprs.replace(/"([A-Za-z_][A-Za-z0-9_]*)"/g, (_m, c) => `${ref}."${c}"`).trim();

const translateAuditBody = (body: string, ref: 'old' | 'new'): string[] => {
  const out: string[] = [];
  for (const m of body.matchAll(
    /INSERT INTO (\w+) \(([^)]+)\)\s*SELECT([^;]+?)FROM OLD\s*(?:WHERE([\s\S]*?))?\s*;/gi,
  )) {
    const [, target, cols, exprs] = m;
    // The WHERE clauses in these bodies only constrain against the transition
    // table itself (tautological per-row); VALUES(old.*) is the SQLite idiom.
    out.push(`insert into ${target} (${cols}) values (${prefixRefs(exprs, ref)});`);
  }
  return out;
};

const TRIGGER_OVERRIDES: Record<string, (tableName: string, action: string) => string[] | undefined> = {
  updated_at: (tableName) => {
    const pk = pkColsOf(tableName);
    if (!pk.length) return undefined;
    const where = pk.map((c) => `"${tableName}"."${c}" = new."${c}"`).join(' and ');
    return [`update "${tableName}" set "updatedAt" = clock_timestamp(), "updateId" = uuidv7() where ${where};`];
  },
  album_user_after_insert: () => [
    `update "album" set "updatedAt" = clock_timestamp(), "updateId" = uuidv7() where "id" = new."albumId" and new."role" <> 'owner';`,
  ],
  album_user_delete: () => [
    `delete from "album" where "album"."id" = old."albumId" and not exists (select "albumId" from "album_user" where "album_user"."albumId" = "album"."id" and "album_user"."role" = 'owner');`,
  ],
  person_user_after_insert: () => [
    `insert into "person" ("ownerId", "personGroupId", "name", "birthDate")
     select new."sharedWithId", new."personGroupId", shared."name", shared."birthDate"
     from "person" shared
     where shared."ownerId" = new."sharedById" and shared."personGroupId" = new."personGroupId"
     on conflict ("ownerId", "personGroupId") do update set
       "name" = case when "person"."name" = '' then excluded."name" else "person"."name" end,
       "birthDate" = coalesce("person"."birthDate", excluded."birthDate")
     where ("person"."name" = '' and excluded."name" <> '') or ("person"."birthDate" is null and excluded."birthDate" is not null);`,
  ],
  person_delete_shares: () => [
    `delete from "person_user" where "person_user"."personGroupId" = old."personGroupId" and "person_user"."sharedWithId" = old."ownerId";`,
  ],
  asset_face_set_asset_state: () => [
    `update "asset_face" set
       "ownerId" = (select "ownerId" from "asset" where "id" = new."assetId"),
       "assetVisibility" = (select "visibility" from "asset" where "id" = new."assetId"),
       "assetDeletedAt" = (select "deletedAt" from "asset" where "id" = new."assetId")
     where "id" = new."id";`,
  ],
  asset_face_update_asset_state: () => [
    `update "asset_face" set "ownerId" = new."ownerId", "assetVisibility" = new."visibility", "assetDeletedAt" = new."deletedAt" where "assetId" = new."id";`,
  ],
  album_asset_delete_audit: () => [
    // PG body guard: only audit when the album parent still exists (direct
    // album_asset deletes); album-cascaded relations must not reach clients.
    // SQLite trigger inserts reject WHERE, so use guarded INSERT..SELECT.
    `insert into album_asset_audit ("albumId", "assetId")
     select * from (select old."albumId", old."assetId")
     where exists (select 1 from "album" where "album"."id" = old."albumId");`,
  ],
  album_user_delete_audit: () => [
    `insert into album_audit ("albumId", "userId") values (old."albumId", old."userId");`,
    `insert into album_user_audit ("albumId", "userId")
     select * from (select old."albumId", old."userId")
     where exists (select 1 from "album" where "album"."id" = old."albumId");`,
  ],
  asset_edit_insert: () => [`update "asset" set "isEdited" = 1 where "id" = new."assetId" and "isEdited" = 0;`],
  asset_edit_delete: () => [
    `update "asset" set "isEdited" = 0 where "id" = old."assetId" and "isEdited" = 1 and not exists (select 1 from "asset_edit" edit where edit."assetId" = "asset"."id");`,
  ],
};

const translateTriggerWhen = (when: unknown, tableName: string): string => {
  if (!when) return '';
  const w = String(when).trim();
  if (/pg_trigger_depth\(\)\s*=\s*0/i.test(w)) return ` when audit_hop('${tableName}') = 0`;
  if (/pg_trigger_depth\(\)\s*<=\s*1/i.test(w)) return ` when audit_hop('${tableName}') <= 1`;
  if (/pg_trigger_depth/.test(w)) {
    report.untranslatedTriggers.push(`when:${w}`);
    return '';
  }
  // row-value comparison: (OLD.a, OLD.b) IS [NOT] DISTINCT FROM (NEW.a, NEW.b)
  const m = /\(([^)]+)\)\s+is\s+(not\s+)?distinct\s+from\s+\(([^)]+)\)/i.exec(w);
  if (m) {
    const olds = m[1].split(',').map((s) => s.trim());
    const news = m[3].split(',').map((s) => s.trim());
    // IS NOT DISTINCT FROM -> fires when every pair is equal (conjunction);
    // IS DISTINCT FROM -> fires when any pair differs (disjunction).
    const negated = !!m[2];
    const op = negated ? ' is ' : ' is not ';
    const joiner = negated ? ' and ' : ' or ';
    const parts = olds.map((o, i) => {
      const oc = o.replace(/OLD\.?\s*\.?"/gi, 'old."').replace(/^"/, 'old."');
      const nc = (news[i] ?? o).replace(/NEW\.?\s*\.?"/gi, 'new."').replace(/^"/, 'new."');
      return `${oc}${op}${nc}`;
    });
    return ' when ' + parts.join(joiner);
  }
  report.untranslatedTriggers.push(`when:${w}`);
  return '';
};

for (const t of schema.tables) {
  for (const tr of t.triggers) {
    if (tr.synchronize === false) continue;
    const actions: string[] = (tr as any).actions ?? [];
    for (const action of actions) {
      if (!['insert', 'update', 'delete'].includes(action)) continue;
      const ref: 'old' | 'new' = action === 'insert' ? 'new' : 'old';
      let statements: string[] | undefined;
      const override = TRIGGER_OVERRIDES[tr.functionName];
      if (override) {
        statements = override(t.name, action);
      } else {
        const body = fnBodies.get(tr.functionName) ?? '';
        const translated = translateAuditBody(body, ref);
        if (translated.length) statements = translated;
      }
      if (!statements || !statements.length) {
        report.untranslatedTriggers.push(`${t.name}.${tr.name} (${action})`);
        continue;
      }
      const timing = 'after';
      const name = `${t.name}_${tr.functionName}_${action}`.replace(/__+/g, '_');
      let when = translateTriggerWhen((tr as any).when, t.name);
      // The updated_at body emulates PG's BEFORE UPDATE trigger. The driver
      // injects `updatedAt = now_iso(), updateId = uuidv7()` into plain UPDATE
      // statements to get BEFORE-semantics for RETURNING; when the statement
      // (or caller) already changed updatedAt, this AFTER body must not fire a
      // second clock tick — that would desync RETURNING from the stored row.
      if (tr.functionName === 'updated_at' && action === 'update') {
        when = when ? `${when} and new."updatedAt" is old."updatedAt"` : ' when new."updatedAt" is old."updatedAt"';
      }
      lines.push(
        `create trigger ${q(name)} ${timing} ${action} on ${q(t.name)} for each row${when} begin\n  ${statements.join('\n  ')}\nend;`,
      );
      report.translatedTriggers.push(name);
    }
  }
}
lines.push('');

const sql = lines.join('\n');
writeFileSync(new URL('../src/schema/schema.sqlite.sql', import.meta.url), sql, 'utf8');
const realStatements = lines.filter((l) => l.trim().length > 0 && !l.startsWith('--') && !l.startsWith('PRAGMA'));
const tsModule = `// Generated by probes/gen-sqlite-schema.ts — do not edit; regenerate.\nexport const SCHEMA_SQLITE = ${JSON.stringify(sql)};\nexport const SCHEMA_SQLITE_STATEMENTS: string[] = ${JSON.stringify(realStatements, null, 2)};\n`;
writeFileSync(new URL('../src/schema/schema.sqlite.ts', import.meta.url), tsModule, 'utf8');
console.error('tables=' + schema.tables.length + ' written_chars=' + sql.length);
console.error(
  JSON.stringify({
    skippedColumns: report.skippedColumns,
    skippedIndexes: report.skippedIndexes,
    skippedTriggers: report.skippedTriggers.length,
    booleanChecks: report.booleanChecks,
  }),
);
